package com.dairum.domain.model

import java.time.LocalDateTime

/**
 * Represents an AI model that can be used for inference
 */
data class AIModel(
    val id: String,
    val name: String,
    val description: String,
    val filePath: String,
    val sizeBytes: Long,
    val modelType: ModelType,
    val quantization: String? = null, // e.g., "Q4_K_M", "Q8_0"
    val contextLength: Int = 2048,
    val isDefault: Boolean = false,
    val isDownloaded: Boolean = false,
    val downloadUrl: String? = null,
    val createdAt: LocalDateTime = LocalDateTime.now(),
    val lastUsedAt: LocalDateTime? = null
) {
    val sizeFormatted: String
        get() {
            val kb = sizeBytes / 1024.0
            val mb = kb / 1024.0
            val gb = mb / 1024.0
            return when {
                gb >= 1 -> String.format("%.1f GB", gb)
                mb >= 1 -> String.format("%.1f MB", mb)
                else -> String.format("%.1f KB", kb)
            }
        }
}

enum class ModelType {
    LLM,        // Language model for text generation
    EMBEDDING   // Embedding model for vector generation
}

/**
 * Embedding for a journal entry
 */
data class JournalEmbedding(
    val id: Long = 0,
    val entryId: Long,
    val embedding: FloatArray,
    val model: String, // Model used to generate embedding
    val version: Int = 1,
    val createdAt: LocalDateTime = LocalDateTime.now(),
    val updatedAt: LocalDateTime = LocalDateTime.now()
) {
    override fun equals(other: Any?): Boolean {
        if (this === other) return true
        if (javaClass != other?.javaClass) return false
        other as JournalEmbedding
        return id == other.id && entryId == other.entryId
    }

    override fun hashCode(): Int {
        var result = id.hashCode()
        result = 31 * result + entryId.hashCode()
        return result
    }
}

/**
 * Result from semantic search
 */
data class RetrievalResult(
    val entry: JournalEntry,
    val score: Float, // Cosine similarity score (0-1)
    val relevanceRank: Int
)

/**
 * AI Query for asking the journal
 */
data class AIQuery(
    val query: String,
    val queryType: QueryType = QueryType.GENERAL,
    val dateRange: DateRange? = null,
    val maxResults: Int = 5,
    val includeMetadata: Boolean = true
)

enum class QueryType {
    GENERAL,           // General question about journal
    MOOD_ANALYSIS,     // Questions about moods
    PATTERN_DETECTION, // Looking for patterns
    REFLECTION,        // Reflective questions
    SUMMARY           // Summarization requests
}

data class DateRange(
    val start: LocalDateTime,
    val end: LocalDateTime
)

/**
 * AI Response container
 */
data class AIResponse(
    val content: String,
    val sources: List<JournalEntry> = emptyList(),
    val confidence: Float = 1.0f,
    val tokensUsed: Int = 0,
    val generationTimeMs: Long = 0,
    val error: String? = null
) {
    val isSuccess: Boolean get() = error == null
}

/**
 * Weekly reflection generated by AI
 */
data class WeeklyReflection(
    val id: Long = 0,
    val weekStartDate: LocalDateTime,
    val weekEndDate: LocalDateTime,
    val summary: String,
    val moodTrend: MoodTrend,
    val keyThemes: List<String>,
    val highlights: List<String>,
    val suggestions: List<String>,
    val entryCount: Int,
    val totalWordCount: Int,
    val createdAt: LocalDateTime = LocalDateTime.now()
)

data class MoodTrend(
    val averageMood: Float,
    val moodRange: Pair<Int, Int>, // min, max
    val dominantMood: String,
    val moodDistribution: Map<String, Int>,
    val trend: TrendDirection
)

enum class TrendDirection {
    IMPROVING,
    DECLINING,
    STABLE,
    FLUCTUATING
}

/**
 * Pattern detection result
 */
data class PatternResult(
    val id: Long = 0,
    val patternType: PatternType,
    val description: String,
    val confidence: Float,
    val evidence: List<PatternEvidence>,
    val insights: List<String>,
    val detectedAt: LocalDateTime = LocalDateTime.now()
)

enum class PatternType {
    MOOD_CORRELATION,      // Mood correlates with something
    TIME_PATTERN,          // Time-based patterns
    ACTIVITY_IMPACT,       // Activities affecting mood
    PEOPLE_IMPACT,         // People affecting mood
    LOCATION_PATTERN,      // Location-based patterns
    WEATHER_CORRELATION,   // Weather affecting mood
    WRITING_HABIT          // Writing frequency patterns
}

data class PatternEvidence(
    val entryId: Long,
    val date: LocalDateTime,
    val factor: String,
    val value: String,
    val mood: Int?
)

/**
 * Smart summary for entries
 */
data class SmartSummary(
    val id: Long = 0,
    val summaryType: SummaryType,
    val period: DateRange,
    val title: String,
    val summary: String,
    val keyPoints: List<String>,
    val moodOverview: String?,
    val topTags: List<String>,
    val topPeople: List<String>,
    val wordCount: Int,
    val entryCount: Int,
    val createdAt: LocalDateTime = LocalDateTime.now()
)

enum class SummaryType {
    DAILY,
    WEEKLY,
    MONTHLY,
    CUSTOM
}

/**
 * Prompt template for AI generation
 */
data class PromptTemplate(
    val name: String,
    val systemPrompt: String,
    val userPromptTemplate: String,
    val maxTokens: Int = 512,
    val temperature: Float = 0.7f,
    val stopTokens: List<String> = emptyList()
)

/**
 * AI generation settings
 */
data class AISettings(
    val selectedModelId: String? = null,
    val selectedEmbeddingModelId: String? = null,
    val maxContextEntries: Int = 10,
    val embeddingSimilarityThreshold: Float = 0.5f,
    val autoUpdateEmbeddings: Boolean = true,
    val cacheResponses: Boolean = true,
    val enablePatternDetection: Boolean = true,
    val weeklyReflectionDay: Int = 0, // 0 = Sunday
    val enableNotifications: Boolean = false
)

/**
 * AI processing status
 */
sealed class AIProcessingStatus {
    object Idle : AIProcessingStatus()
    object LoadingModel : AIProcessingStatus()
    data class GeneratingEmbeddings(val progress: Float, val current: Int, val total: Int) : AIProcessingStatus()
    object Searching : AIProcessingStatus()
    object Generating : AIProcessingStatus()
    data class Error(val message: String) : AIProcessingStatus()
    object Complete : AIProcessingStatus()
}
